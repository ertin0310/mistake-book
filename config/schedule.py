"""调度相关的可调参数：间隔台阶、每日上限范围、掌握度四格口径。

改数值只动这个文件，不碰 `domain/scheduling/ladder.py`。
"""

# 台阶序列：下标 = step_index，值 = 该级对应的间隔天数。
# 顶格是 7（60 天），所以"已稳住"用台阶定义，不再引入第二个"掌握度"字段。
LADDER_INTERVALS = [0, 1, 2, 4, 7, 15, 30, 60]

ALGORITHM_VERSION = "ladder-1"

# 自评四档 → 台阶怎么动。1 最好、4 最差，与 config/prompts.py 的档位文案一一对应。
# 1 升两级 / 2 升一级 / 3 退一级（不低于 0）/ 4 归零并记一次 lapse。
#
# ★ 3 为什么不能写 0：级数不动 = 间隔不变 = 下次到期日还是今天，
#   这道题当天刷完立刻又回到今日队列，出不去，除非用户改评别的档。
#   方案里"原地缩回"这四个字本来就含糊，这里取"退一级"这一种解释
#   （由 ladder.py 夹在 0 与顶格之间）。
LADDER_STEPS = {1: 2, 2: 1, 3: -1, 4: "reset"}

# ★ 评完之后至少隔这么天才能再排。台阶第 0 级的间隔是 0 天，那是给"新入队当天就
#   出现在今日复习"用的（v7 三-13）；**评完**还落回第 0 级的话，到期日会等于今天，
#   这道题当天刷完立刻回到队列里出不去——v7 三-4 拒绝"原地不动"用的正是这条理由，
#   所以它同样适用于"退一级退到 0"和"归零"这两种情况。（2026-10-22 定的甲）
MIN_INTERVAL_AFTER_REVIEW = 1

DAILY_CAP_MIN = 1
DAILY_CAP_MAX = 200
DAILY_CAP_DEFAULT = 30

# 耗时判档的倍率区间：以该科目历史耗时中位数为基准，(上限倍数, 档位)。
# 取第一个"耗时 <= 上限"的档位；None 表示不设上限。
DURATION_RATIO_BANDS = [(0.6, 1), (1.2, 2), (2.0, 3), (None, 4)]

# 离群点裁剪：单次耗时超过这个秒数就按上限记，避免一次挂机把整科中位数拖飞。
DURATION_CAP_SECONDS = 1800

# 历史流水不足这么多条就**不做耗时预选**：拿三条样本算出来的"中位数"是噪声，
# 用它替用户选档位比不选更糟。
DURATION_MIN_SAMPLES = 10

# 填空题判分口径（三-2）：三条都放配置，改口径不碰代码。
BLANK_ORDER_MATTERS = True      # False = 只要求"填进去的答案集合"与标准答案集合一致
BLANK_PARTIAL_CREDIT = True     # False = 有一空不对就整题算错
# 判分时忽略的东西：大小写、全半角、空格。标点不忽略（"1, 2" 与 "12" 是两回事）。
BLANK_IGNORE_CASE = True
BLANK_IGNORE_SPACES = True

# 掌握度分布的四格：区间左闭右开，按 mistake.step_index 分。
MASTERY_BANDS = [
    ("not_started", "没开始", 0, 1),
    ("just_started", "刚上手", 1, 3),
    ("on_the_way", "在路上", 3, 6),
    ("settled", "已稳住", 6, 8),
]
